/**
 * Supabase data layer for TrustOrder (async, fail-closed).
 *
 * This is the replacement for db.js local JSON. It has the same
 * method names as db.js where possible, but every method is async
 * because Supabase is remote. Callers MUST await it. A synchronous
 * db.js call cannot be swapped for this file one-for-one; see
 * SUPABASE_MIGRATION.md for the route-by-route conversion map.
 *
 * Rules:
 * - Env only: SUPABASE_URL + SUPABASE_SERVICE_KEY (see supabaseClient).
 * - If Supabase is not configured, every method throws an error with
 *   code NOT_CONFIGURED. It never falls back to local JSON.
 * - IDs are UUIDs generated by Supabase, NOT the old sel_/ord_/call_
 *   string ids from db.js. Old local ids must not be copied to Supabase.
 * - Passwords are never stored in plaintext. createSeller accepts
 *   password_hash only; a plaintext `password` field is ignored.
 * - Wallet balance is derived from wallet_transactions where possible.
 *   updateSellerWallet is a read-modify-write and is NOT atomic;
 *   concurrent top-ups must be serialised by the caller until a
 *   Postgres function / RPC replaces it (see SUPABASE_MIGRATION.md).
 * - OTP codes are never stored. otp_verifications stores status only.
 */

const crypto = require('crypto');
const { getSupabaseClient } = require('./supabaseClient');

function notConfigured() {
  const err = new Error('SUPABASE_NOT_CONFIGURED: set SUPABASE_URL and SUPABASE_SERVICE_KEY in env only');
  err.code = 'NOT_CONFIGURED';
  return err;
}

function clientOrThrow() {
  const sb = getSupabaseClient();
  if (!sb) throw notConfigured();
  return sb;
}

function hashPhone(phone) {
  const normalized = String(phone).replace(/[^\d+]/g, '');
  return crypto.createHash('sha256').update(normalized).digest('hex');
}

function toNumber(v, fallback = 0) {
  const n = Number(v);
  return Number.isFinite(n) ? n : fallback;
}

function mapSeller(row) {
  if (!row) return null;
  return {
    ...row,
    name: row.name || row.brand_name,
    wallet_balance_inr: toNumber(row.wallet_balance_inr, 0),
  };
}

function mapOrder(row) {
  if (!row) return null;
  return { ...row, cod_amount: toNumber(row.cod_amount, 0), risk_score: toNumber(row.risk_score, 50) };
}

// --- Sellers ---
async function getSeller(id = null) {
  if (!id) return null;
  const sb = clientOrThrow();
  const { data, error } = await sb.from('sellers').select('*').eq('id', id).maybeSingle();
  if (error) throw error;
  return mapSeller(data);
}

async function getSellerByEmail(email) {
  if (!email) return null;
  const sb = clientOrThrow();
  const { data, error } = await sb.from('sellers').select('*').eq('email', email.toLowerCase().trim()).maybeSingle();
  if (error) throw error;
  return mapSeller(data);
}

async function getSellerByShopifyDomain(domain) {
  if (!domain) return null;
  const sb = clientOrThrow();
  const clean = domain.trim().toLowerCase();
  const { data, error } = await sb.from('sellers').select('*').ilike('shopify_domain', `%${clean}%`).limit(1).maybeSingle();
  if (error) throw error;
  return mapSeller(data);
}

async function getAllSellers() {
  const sb = clientOrThrow();
  const { data, error } = await sb.from('sellers').select('id,brand_name,name,email,phone,shopify_domain,wallet_balance_inr,plan_tier,created_at').order('created_at', { ascending: false });
  if (error) throw error;
  return (data || []).map(mapSeller);
}

async function createSeller(sellerData) {
  const sb = clientOrThrow();
  const payload = {
    name: sellerData.name || sellerData.brand_name || 'Store Founder',
    email: (sellerData.email || '').toLowerCase().trim(),
    brand_name: (sellerData.brand_name || 'My Store').trim(),
    phone: sellerData.phone || '',
    shopify_domain: sellerData.shopify_domain || '',
    shopify_access_token: sellerData.shopify_access_token || null,
    shiprocket_token: sellerData.shiprocket_token || null,
    wallet_balance_inr: 0,
    plan_tier: 'pay_as_you_go',
    upi_trust_lock_amount: 19,
    total_orders_processed: 0,
    rto_cut_percentage: null,
  };
  if (sellerData.password_hash) payload.password_hash = sellerData.password_hash;
  // Plaintext `password` is deliberately ignored. Never store it.
  const { data, error } = await sb.from('sellers').insert([payload]).select().single();
  if (error) throw error;
  return mapSeller(data);
}

async function updateSellerWallet(sellerId, amountDelta) {
  const sb = clientOrThrow();
  const seller = await getSeller(sellerId);
  if (!seller) return null;
  const next = Number((seller.wallet_balance_inr + amountDelta).toFixed(2));
  const { data, error } = await sb.from('sellers').update({ wallet_balance_inr: next }).eq('id', sellerId).select().single();
  if (error) throw error;
  return mapSeller(data);
}

// --- Orders ---
async function getOrders(sellerId = null) {
  const sb = clientOrThrow();
  let q = sb.from('orders').select('*').order('created_at', { ascending: false });
  if (sellerId) q = q.eq('seller_id', sellerId);
  const { data, error } = await q;
  if (error) throw error;
  return (data || []).map(mapOrder);
}

async function getOrderById(id) {
  const sb = clientOrThrow();
  let { data, error } = await sb.from('orders').select('*').eq('id', id).maybeSingle();
  if (error) throw error;
  if (!data) {
    ({ data, error } = await sb.from('orders').select('*').eq('external_order_id', id).maybeSingle());
    if (error) throw error;
  }
  return mapOrder(data);
}

