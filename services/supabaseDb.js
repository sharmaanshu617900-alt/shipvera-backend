// --- Buyer trust graph ---
async function getBuyerTrust(phone) {
  const hash = hashPhone(phone);
  const sb = clientOrThrow();
  const { data, error } = await sb.from('buyer_trust_graph').select('*').eq('phone_hash', hash).maybeSingle();
  if (error) throw error;
  if (data) return data;
  return {
    phone_hash: hash, total_cod_orders: 1, verified_count: 0,
    fake_cancel_count: 0, upi_trust_paid_count: 0,
    global_risk_level: 'neutral', last_seen_at: new Date().toISOString(),
  };
}

async function recordBuyerOutcome(phone, outcome) {
  const sb = clientOrThrow();
  const hash = hashPhone(phone);
  const existing = await sb.from('buyer_trust_graph').select('*').eq('phone_hash', hash).maybeSingle();
  const rec = existing.data || {
    phone_hash: hash, total_cod_orders: 0, verified_count: 0,
    fake_cancel_count: 0, upi_trust_paid_count: 0, global_risk_level: 'neutral',
  };
  rec.total_cod_orders = (rec.total_cod_orders || 0) + 1;
  rec.last_seen_at = new Date().toISOString();
  if (outcome === 'VERIFIED_GENUINE') rec.verified_count = (rec.verified_count || 0) + 1;
  else if (outcome === 'CANCEL_REQUESTED') rec.fake_cancel_count = (rec.fake_cancel_count || 0) + 1;
  else if (outcome === 'TRUST_LOCK_PAID') rec.upi_trust_paid_count = (rec.upi_trust_paid_count || 0) + 1;
  if (rec.fake_cancel_count >= 2 && rec.fake_cancel_count > rec.verified_count) rec.global_risk_level = 'habitual_timepasser';
  else if (rec.verified_count >= 3 && rec.fake_cancel_count === 0) rec.global_risk_level = 'trusted';
  else rec.global_risk_level = 'neutral';
  const { data, error } = await sb.from('buyer_trust_graph').upsert([rec], { onConflict: 'phone_hash' }).select().single();
  if (error) throw error;
  return data;
}

