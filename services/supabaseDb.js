// --- Analytics (computed, never a claimed RTO rate) ---
async function getAnalytics(sellerId = null) {
  const seller = sellerId ? await getSeller(sellerId) : null;
  const orders = seller ? await getOrders(seller.id) : [];
  const totalOrders = orders.length;
  const verifiedOrders = orders.filter((o) => o.verification_status === 'verified_cleaned' || o.verification_status === 'trust_lock_paid').length;
  const fakeBlockedOrders = orders.filter((o) => o.verification_status === 'cancelled_fake').length;
  const totalMoneySaved = orders.reduce((s, o) => s + toNumber(o.rto_money_saved, 0), 0);
  const pendingOrders = orders.filter((o) => ['queued', 'calling', 'trust_lock_sent'].includes(o.verification_status)).length;
  let avgCallDuration = 0;
  let avgCallCost = null;
  if (orders.length) {
    const logs = [];
    for (const o of orders) logs.push(...(await getCallLogs(o.id)));
    const durations = logs.map((l) => toNumber(l.duration_seconds, 0)).filter((d) => d > 0);
    const costs = logs.map((l) => toNumber(l.call_cost_inr, NaN)).filter((c) => Number.isFinite(c));
    if (durations.length) avgCallDuration = Math.round(durations.reduce((a, b) => a + b, 0) / durations.length);
    if (costs.length) avgCallCost = Number((costs.reduce((a, b) => a + b, 0) / costs.length).toFixed(2));
  }
  return {
    seller_id: seller ? seller.id : null,
    seller_brand: seller ? seller.brand_name : null,
    wallet_balance_inr: seller ? seller.wallet_balance_inr : 0,
    total_orders_protected: totalOrders,
    verified_orders: verifiedOrders,
    fake_blocked_orders: fakeBlockedOrders,
    pending_orders: pendingOrders,
    rto_money_saved_inr: totalMoneySaved,
    // Share of orders reaching a verified/cancelled outcome. NOT a
    // measured RTO reduction rate; that needs a baseline comparison.
    rto_reduction_rate_pct: totalOrders > 0 ? Math.round(((verifiedOrders + fakeBlockedOrders) / totalOrders) * 100) : 0,
    avg_call_duration_seconds: avgCallDuration,
    cost_per_verified_order_inr: avgCallCost,
  };
}

